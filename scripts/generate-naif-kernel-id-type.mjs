#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const REPO_ROOT = path.resolve(process.cwd());

const IDS_JSON_PATH = path.join(REPO_ROOT, "scripts/naif-generic-kernel-leaf-paths.json");
const OUTPUT_TS_PATH = path.join(REPO_ROOT, "packages/tspice/src/kernels/naifKernelId.ts");

function usage() {
  return [
    "Usage: node scripts/generate-naif-kernel-id-type.mjs",
    "",
    `Reads:  ${IDS_JSON_PATH}`,
    `Writes: ${OUTPUT_TS_PATH}`,
    "",
    "Options:",
    "  -h, --help   Show help",
  ].join("\n");
}

/** @param {unknown} parsed */
function parseIdsJson(parsed) {
  if (!Array.isArray(parsed)) {
    throw new Error(`Expected JSON array in ${IDS_JSON_PATH}`);
  }

  const ids = parsed.map((v, i) => {
    if (typeof v !== "string") {
      throw new Error(
        `Expected string at index ${i} in ${IDS_JSON_PATH} (got ${typeof v})`,
      );
    }
    const trimmed = v.trim();
    if (!trimmed) {
      throw new Error(`Expected non-empty string at index ${i} in ${IDS_JSON_PATH}`);
    }
    if (trimmed !== v) {
      throw new Error(
        `Kernel id at index ${i} in ${IDS_JSON_PATH} has leading/trailing whitespace: ${JSON.stringify(v)}`,
      );
    }
    return v;
  });

  const seen = new Set();
  /** @type {string[]} */
  const dupes = [];
  for (const id of ids) {
    if (seen.has(id)) dupes.push(id);
    seen.add(id);
  }

  if (dupes.length) {
    throw new Error(
      `Found ${dupes.length} duplicate kernel ids in ${IDS_JSON_PATH}:\n` +
        dupes.slice(0, 50).map((d) => `- ${d}`).join("\n") +
        (dupes.length > 50 ? `\n... (${dupes.length - 50} more)` : ""),
    );
  }

  // Keep output stable even if the source JSON is out of order.
  ids.sort((a, b) => a.localeCompare(b));

  return ids;
}

async function main() {
  const args = new Set(process.argv.slice(2));

  if (args.has("--help") || args.has("-h")) {
    process.stdout.write(usage() + "\n");
    process.exit(0);
  }

  const raw = await readFile(IDS_JSON_PATH, "utf8");

  /** @type {unknown} */
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(
      `Failed to parse JSON at ${IDS_JSON_PATH}: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  const ids = parseIdsJson(parsed);

  const header = [
    "// This file is generated by `node scripts/generate-naif-kernel-id-type.mjs`.",
    "// Do not edit manually.",
    "",
  ].join("\n");

  const union = ids.map((id) => `  | ${JSON.stringify(id)}`).join("\n");

  const out = `${header}export type NaifKernelId =\n${union};\n`;

  await mkdir(path.dirname(OUTPUT_TS_PATH), { recursive: true });
  await writeFile(OUTPUT_TS_PATH, out, "utf8");

  process.stdout.write(
    `Wrote ${ids.length} NaifKernelId entries -> ${path.relative(REPO_ROOT, OUTPUT_TS_PATH)}\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`${err instanceof Error ? err.stack ?? err.message : String(err)}\n`);
  process.exit(1);
});
